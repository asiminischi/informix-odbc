#pragma once

#include "sqli/error.h"
#include "sqli/handshake.h"
#include "sqli/transport.h"

#include <cstddef>
#include <cstdint>
#include <expected>
#include <optional>
#include <span>
#include <string>
#include <vector>

namespace ifxsqli {

// A live SQLI session: transport + completed handshake. Phase 1 scope only
// covers connect/disconnect; statement traffic is Phase 2.
class SqliConnection {
public:
    [[nodiscard]] static std::expected<SqliConnection, Error> connect(const std::string& host, int port,
                                                                       const ConnectParams& params);

    // Sends SQ_EXIT and waits for the server's acknowledgement, per the
    // confirmed disconnect sequence in docs/protocol-notes.md. Safe to call
    // at most once; the destructor closes the socket unconditionally as a
    // fallback if this wasn't called.
    [[nodiscard]] std::expected<void, Error> disconnectOrderly();

    [[nodiscard]] const ConnectResult& serverInfo() const { return info_; }

    // Whether the connection negotiated the "wide" SQ_PROTOCOLS capability
    // set. Despite the name, this gates more than just DESCRIBE's 4-byte
    // offset fields (bit 50) - it's used as a single proxy for several
    // distinct capability bits (isUSVER, is2GBFetchBufferSupported, isFetchArr,
    // etc.) that all happen to co-occur as true on every server tested so far.
    // Only bit 50 is actually inspected; the others are assumed to track it.
    // If a server is ever found where they diverge, this needs to become
    // several independent flags - see docs/protocol-notes.md.
    [[nodiscard]] bool has4ByteOffsets() const { return has4ByteOffsets_; }

    // Whether SQ_GETROUTINE's named-parameters wire framing applies (see
    // sqli/connection.cpp's ProtocolCapabilities doc comment) - consulted by
    // the fastpath RPC subsystem (sqli/fastpath.cpp) that smart LOBs (BLOB/
    // CLOB) need. Confirmed live: set on this project's IDS 14.10 dev
    // container.
    [[nodiscard]] bool namedParametersSupported() const { return namedParametersSupported_; }

    // Sends a simple, resultless SQL command (e.g. "set isolation to ...")
    // and waits for it to complete. Distinct from SqliStatement because the
    // wire shape is different: prepare+execute+release happen as one batch
    // rather than as separate steps.
    [[nodiscard]] std::expected<void, Error> executeCommand(const std::string& sql);

    // Transaction control (SQ_BEGIN/SQ_CMMTWORK/SQ_RBWORK), confirmed live -
    // see docs/protocol-notes.md's Transactions section. Each sends the
    // opcode (SQ_RBWORK also sends a trailing savepoint id) + EOT and reads
    // the generic tagged-record response (DONE/ERROR/COST/SQ_XACTSTAT), the
    // same shape executeCommand uses for its own reply, since no SQL text
    // or DESCRIBE is involved.
    [[nodiscard]] std::expected<void, Error> beginTransaction();
    [[nodiscard]] std::expected<void, Error> commitTransaction();
    [[nodiscard]] std::expected<void, Error> rollbackTransaction();

    // The serial/bigserial value generated by the most recent executeCommand
    // that was an INSERT (SQ_INSERTDONE, confirmed live - see
    // docs/protocol-notes.md). nullopt if the last command wasn't an INSERT.
    // **Confirmed live to read back as 0, not the real generated value**,
    // for a plain INSERT even into a table with a SERIAL column - the
    // decompiled JDBC source only populates this meaningfully when the
    // statement additionally requests "SGK" (statement generated keys, the
    // JDBC Statement.RETURN_GENERATED_KEYS mechanism) via a separate
    // sendSGKPrepare request this driver doesn't send (not implemented -
    // Phase 5+). Don't rely on this for a real last-inserted-identity value
    // yet; it's wired up now purely so SQ_INSERTDONE's bytes are consumed
    // correctly rather than desyncing the stream.
    [[nodiscard]] std::optional<std::int64_t> lastSerialInserted() const { return lastSerialInserted_; }
    [[nodiscard]] std::optional<std::int64_t> lastBigSerialInserted() const { return lastBigSerialInserted_; }

    // Fetches a simple large object's (BYTE/TEXT, ifxtype::kByte/kText)
    // actual content, given the opaque 56-byte descriptor a TUPLE row
    // carries for that column instead of the value itself (see
    // sqli/types.h's kSimpleLobDescriptorSize doc comment). `descriptor`
    // must be exactly that 56-byte slice, echoed back verbatim - this
    // driver never interprets it, only round-trips it, matching the
    // decompiled JDBC reference. Sends SQ_FETCHBLOB(38) + the descriptor,
    // then concatenates every SQ_BLOB(39) response chunk until SQ_EOT.
    // Confirmed live (tools/ifx_probe, both BYTE and TEXT, NULL, and a
    // 200KB multi-chunk value) - see docs/protocol-notes.md's Simple LOB
    // section.
    //
    // The real precondition is "no response currently mid-stream on this
    // connection" (SQ_FETCHBLOB is a standalone request/response exchange
    // that can't interleave with another in-flight one), not "not inside a
    // fetch loop" per se - SqliStatement::fetchRow's underlying batch read
    // already drains its whole response to SQ_EOT before returning any
    // row, so calling this once fetchRow has returned (even repeatedly,
    // once per row, as tools/ifx_probe does) is safe. NOT yet confirmed
    // live: a result set large enough to span multiple server-side fetch
    // batches, where the main cursor's own fetch protocol might not be
    // fully idle the way a small, single-batch result set's is.
    [[nodiscard]] std::expected<std::vector<std::byte>, Error> fetchSimpleLob(std::span<const std::byte> descriptor);

    // Fetches a smart large object's (BLOB/CLOB, ifxtype::kBoolean's shared
    // wire type 41 - distinguished from BOOLEAN by ColumnDesc::extendedTypeName
    // being "blob"/"clob") actual content, given the 72-byte IfxLocator
    // payload a TUPLE row carries for that column. `locatorPayload` must be
    // exactly [4-byte big-endian length=72][72-byte locator bytes] - a
    // smart-LOB TUPLE column's own raw slice with just the leading 1-byte
    // null-flag stripped off (see docs/protocol-notes.md's Smart large
    // objects section for the full row shape) - which is also, conveniently,
    // exactly IfxBaseType.toIfx()'s own non-null bind-parameter encoding, so
    // it round-trips into SQ_BIND with no re-encoding.
    //
    // Unlike simple LOBs (a dedicated two-opcode fetch), smart LOBs need a
    // whole fastpath RPC subsystem: resolves and calls
    // informix.ifx_lo_open(blob, integer) to get a file descriptor, reads
    // the entire value via SQ_LODATA, then calls
    // informix.ifx_lo_close(integer) - three separate round trips.
    // Confirmed live against this project's IDS 14.10 dev container, cross-
    // checked against a real JDBC driver (jdbc-4.50.10.jar) protocol trace
    // (SQLIDEBUG-equivalent TRACEFILE/TRACE connection properties) doing the
    // same open/read/close sequence - see docs/protocol-notes.md for the
    // full byte-level writeup, including two confirmed asymmetries from
    // this driver's other bind conventions: fastpath INTEGER parameters and
    // return values use precision field 2560 (not the 4 ordinary INTEGER
    // binds use elsewhere), and the locator UDT parameter's extended owner
    // is the empty string (not "informix", unlike BOOLEAN's bind).
    [[nodiscard]] std::expected<std::vector<std::byte>, Error> fetchSmartLob(std::span<const std::byte> locatorPayload);

    // Exposed for SqliStatement (sqli/statement.h), which sits on top of the
    // same connection and needs to send/receive statement-protocol messages
    // over it directly.
    [[nodiscard]] TcpSocket& transport() { return sock_; }

private:
    SqliConnection(TcpSocket sock, ConnectResult info, bool has4ByteOffsets, bool namedParametersSupported)
        : sock_(std::move(sock)), info_(std::move(info)), has4ByteOffsets_(has4ByteOffsets),
          namedParametersSupported_(namedParametersSupported) {}

    TcpSocket sock_;
    ConnectResult info_;
    bool has4ByteOffsets_ = false;
    bool namedParametersSupported_ = false;
    std::optional<std::int64_t> lastSerialInserted_;
    std::optional<std::int64_t> lastBigSerialInserted_;
};

} // namespace ifxsqli
